import { readFile, writeFile } from "node:fs/promises";
const path = "tests/extension-smoke-cdp.mjs";
let source = await readFile(path, "utf8");
const previous = "neptune-hermes-test-key";
const replacement = "neptune-hermes-test-key-123456";
if (!source.includes(previous) && source.includes(replacement)) process.exit(0);
if (!source.includes(previous)) throw new Error("Managed Hermes smoke key target not found");
source = source.replaceAll(previous, replacement);
await writeFile(path, source, "utf8");
console.log("Managed Hermes smoke key updated.");
